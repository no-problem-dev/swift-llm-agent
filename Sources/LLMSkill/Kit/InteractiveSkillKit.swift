                ```

                ## 完了時の最終出力
                ユーザーが「これで完了」を選択したら、最後のテキスト出力としてジャーナルの完全版を出力してください。この出力がセッションの最終記録になります。

                ```
                📔 今日のジャーナル（2026年3月1日）

                **出来事**
                - [ユーザーが話した出来事を箇条書き]

                **感情**
                - [表現された感情]

                **客観データ**
                - 今日の予定: [件数]件（[主な予定]）
