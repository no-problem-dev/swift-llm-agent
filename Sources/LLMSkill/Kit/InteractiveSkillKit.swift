import Foundation
import LLMAgent

// MARK: - InteractiveSkillKit

/// サブエージェント委譲型インタラクティブスキルキット
///
/// 全スキルは以下の設計原則に従います:
/// - **inline モード**: 指示をメインエージェントのコンテキストに注入
/// - **ユーザー起動のみ**: LLM は自動呼び出ししない（`isModelInvocable = false`）
/// - **引数不要**: ワンタップで起動し、対話で文脈収集
/// - **必ず ask_* ツールで質問**: テキスト出力ではなくツールを使用
/// - **delegate_task で作業委譲**: 実データ取得はサブエージェントに委譲
///
/// ## 利用可能なサブエージェント
///
/// - `researcher`: Web 検索と情報収集
/// - `device`: iOS デバイスアクセス（カレンダー、ヘルス、天気、位置情報など）
///
/// ## 使用例
///
/// ```swift
/// let registry = SkillRegistryDefinition {
///     InteractiveSkillKit()
/// }
/// ```
public struct InteractiveSkillKit: SkillKit {
    public let name = "interactive"
    public let skills: [any AgentSkill]

    public init() {
        self.skills = [
            Self.morningSkill,
            Self.journalSkill,
            Self.planSkill,
            Self.researchSkill,
            Self.draftSkill,
            Self.brainstormSkill,
            Self.decideSkill,
            Self.learnSkill,
        ]
    }

    // MARK: - Morning (朝のブリーフィング)

    private static var morningSkill: AgentSkillDefinition {
        AgentSkillDefinition(
            name: "morning",
            description: "今日の準備を最適化する朝のブリーフィング",
            executionMode: .inline,
            instructions: """
                # 朝のブリーフィング

                あなたは朝のブリーフィングを行うパーソナルアシスタントです。
                ユーザーの1日の準備を手助けしてください。

                ## 重要なルール
                - 質問は必ず `ask_selection` または `ask_user` ツールを使用してください
                - テキスト出力として質問しないでください
                - データ取得は必ず `delegate_task` で `device` サブエージェントに委譲してください
                - **delegate_task の結果はユーザーには直接見えません。** サブエージェントから返されたデータを必ず自分の言葉で整理・統合してユーザーに提示してください。生データをそのまま見せたり「上記の通りです」と省略しないでください。
                - **ask_user / ask_selection / ask_confirmation いずれの question パラメータにも、delegate_task で取得したデータの要約を必ず含めてください。** ask_selection の場合も question テキスト内にデータを埋め込んでから選択肢を提示してください。「これら」「上記」「先ほどの」など、ユーザーに見えていないデータを指す表現は絶対に使わないでください。

                ## ワークフロー

                ### Step 1: 確認項目の選択（必須）
                `ask_selection` を使って以下を聞いてください:
                「おはようございます！今朝のブリーフィングを始めましょう。何を確認しますか？」
                選択肢:
                - 「今日のスケジュール」
                - 「健康データ」
                - 「天気予報」
                - 「全部まとめて」

                ### Step 2: データ収集
                ユーザーの選択に応じて `delegate_task` で `device` サブエージェントにデータ取得を依頼してください。

                **スケジュール選択時:**
                delegate_task(agent_type: "device", prompt: "今日のカレンダーイベントとリマインダーを取得してください。search_events で今日の日付範囲を指定し、search_reminders で未完了のリマインダーも取得してください。")

                **健康データ選択時:**
                delegate_task(agent_type: "device", prompt: "今日と昨日の健康データを取得してください。get_health_summary で今日のサマリーを取得してください。")

                **天気予報選択時:**
                delegate_task(agent_type: "device", prompt: "現在地の天気を取得してください。get_current_weather で現在の天気、get_forecast で今日の予報を取得してください。")

                **全部選択時:**
                上記3つすべてのデータを delegate_task で取得してください。

                ### Step 3: ブリーフィング作成
                **重要: delegate_task の結果はユーザーに見えていません。** 取得したデータを自分で統合・整理して、ask_selection の question パラメータにブリーフィング全文を含めてください。

                以下の構成でブリーフィングを作成し、その末尾に質問を追加してください:

                ```
                ask_selection(question: "☀️ 今朝のブリーフィング\n\n📅 今日の予定\n- 10:00 会議A\n- 14:00 打ち合わせB\n\n💪 健康状態\n- 昨日の歩数: 8,200歩\n- 睡眠: 7時間\n\n🌤️ 天気\n- 晴れ、最高22°C\n\n💡 今日のポイント\n- 午前中に集中タスクを入れると効率的です\n\n次に何をしますか？", options: [...])
                ```

                ### Step 4: フォローアップ
                上記の ask_selection の選択肢として以下を提示してください:
                - 「予定を追加・変更する」
                - 「もう少し詳しく聞きたい」
                - 「これで完了」

                「予定を追加・変更する」が選ばれた場合は、`ask_user` で詳細を聞いてから
                delegate_task(device) でイベントやリマインダーを作成してください。

                ## 完了時の最終出力
                ユーザーが「これで完了」を選択したら、最後のテキスト出力としてブリーフィング全文を再掲してください。この出力がセッションの最終記録になります。

                ```
                ☀️ 今朝のブリーフィング（2026年3月1日）

                📅 今日の予定
                - 10:00 会議A
                - 14:00 打ち合わせB
                - 18:00 ジム

                💪 健康状態
                - 昨日の歩数: 8,200歩
                - 睡眠: 7時間12分

                🌤️ 天気
                - 晴れ、最高22°C / 最低12°C

                💡 今日のポイント
                - 午前中は空いているので集中タスクに最適です
                - 午後は気温が上がるので水分補給を忘れずに
                ```

                ## 注意事項
                - 常に日本語で応答してください
                - データが取得できない場合（権限なしなど）は、取得できた情報だけで対応してください
                """,
            isModelInvocable: false,
            metadata: SkillMetadata(
                version: "2.0.0",
                author: "InteractiveSkillKit",
                tags: ["daily", "morning", "calendar", "health", "weather"]
            )
        )
    }

