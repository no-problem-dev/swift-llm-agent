import Foundation
import LLMAgent

// MARK: - GeneralPurposeSkillKit

/// 汎用インタラクティブスキルキット
///
/// 日常的なタスクに使えるワークフロー型スキルを提供します。
/// すべてのスキルは `inline` モードで、ユーザーとの対話を通じて
/// コンテキストを収集し、適切な出力を生成します。
///
/// ## ワークフロー設計原則
///
/// 各スキルは以下の 4 ステップで構成:
/// 1. **文脈収集**: 1〜2 個ずつ段階的に質問
/// 2. **合意確認**: 方向性の確認
/// 3. **実行・提示**: 構造化フォーマットで出力
/// 4. **フォローアップ**: 深掘り・修正・次のステップの選択肢提示
///
/// ## 使用例
///
/// ```swift
/// let registry = SkillRegistryDefinition {
///     BuiltInSkillKit()
///     GeneralPurposeSkillKit()
/// }
/// ```
public struct GeneralPurposeSkillKit: SkillKit {
    public let name = "general-purpose"
    public let skills: [any AgentSkill]

    public init() {
        self.skills = [
            Self.draftSkill,
            Self.brainstormSkill,
            Self.researchSkill,
            Self.translateSkill,
            Self.compareSkill,
            Self.decideSkill,
            Self.journalSkill,
            Self.learnSkill,
            Self.recipeSkill,
            Self.travelSkill,
            Self.presentSkill,
            Self.reviewTextSkill,
        ]
    }

